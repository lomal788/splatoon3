/** 집합 S: 이동 코드가 오징어 속도 경로를 쓰는 상태 (movement_physics.md §4.2). */
export function isSquidMove(s: number): boolean {
  return (s >= 0x82 && s <= 0x90) || (s >= 0xaa && s <= 0xac) || s === 0xed || s === 0xee || s === 0x10c;
}

/** 집합 Q: 상태기계의 "지금 오징어" (S ∪ 0xb8..0xba). */
export function isSquidSM(s: number): boolean {
  return isSquidMove(s) || (s >= 0xb8 && s <= 0xba);
}
